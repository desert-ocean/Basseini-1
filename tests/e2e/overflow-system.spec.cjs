const { test, expect } = require('@playwright/test');

test('overflow article calculators, responsive illustration and shared actions', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  await page.goto('/spravochnik/kak-rabotaet-perelivnaya-sistema.html');
  await page.setViewportSize({ width: 390, height: 900 });
  await expect(page.locator('h1')).toContainText('Как работает переливная система бассейна');
  await expect(page.locator('form[action="https://api.alpool.ru/api/leads"]')).toBeAttached();
  await expect(page.locator('a.contact-cta__button[href="/tehnicheskoe-zadanie/"]')).toBeAttached();
  await expect(page.locator('.overflow-toc a[href="#outlet-calculator"]')).toHaveAttribute('href', '#outlet-calculator');
  expect(await page.locator('#choice .table-wrap').evaluate(el => el.scrollWidth > el.clientWidth)).toBeTruthy();
  await expect(page.locator('[data-trough-calculator] [data-result="areaCm2"]')).toContainText('795');
  await expect(page.locator('[data-outlet-calculator] [data-result="recommendedCount"]')).toContainText('12');
  await page.locator('[data-trough-calculator] [data-field="category"]').selectOption('teaching');
  await expect(page.locator('[data-trough-calculator] [data-result="areaCm2"]')).toContainText('445');
  await page.locator('[data-trough-calculator] [data-field="category"]').selectOption('general');
  await page.locator('[data-trough-calculator] [data-field="outlets"]').fill('0');
  await expect(page.locator('[data-trough-calculator] [data-error]')).toBeVisible();
  await page.locator('[data-trough-calculator] [data-field="outlets"]').fill('12');
  await expect(page.locator('[data-trough-calculator] [data-error]')).toBeHidden();
  await page.locator('.overflow-toc a[href="#outlet-calculator"]').click();
  await expect(page).toHaveURL(/#outlet-calculator$/);
  await page.locator('[data-outlet-calculator] [data-field="geometry"]').selectOption('loop');
  await page.locator('[data-outlet-calculator] [data-field="totalLengthM"]').fill('24');
  await expect(page.locator('[data-outlet-calculator] [data-result="geometryCount"]')).toContainText('12');
  await expect(page.locator('[data-outlet-calculator] [data-segments]')).not.toContainText('NaN');
  await page.locator('[data-outlet-calculator] [data-field="geometry"]').selectOption('segments');
  await page.locator('[data-outlet-calculator] [data-field="flowM3h"]').fill('1');
  await page.locator('[data-outlet-calculator] [data-field="segmentLengths"]').fill('5,1; 1.5; 3,3');
  await expect(page.locator('[data-outlet-calculator] [data-result="totalLengthM"]')).toContainText('9,9');
  await expect(page.locator('[data-outlet-calculator] [data-result="geometryCount"]')).toContainText('6');
  await expect(page.locator('[data-outlet-calculator] [data-result="recommendedCount"]')).toContainText('6');
  expect(await page.locator('[data-outlet-calculator] [data-segments] .table-wrap').evaluate(el => el.scrollWidth > el.clientWidth)).toBeTruthy();
  await page.locator('[data-outlet-calculator] [data-field="segmentLengths"]').fill('7,5; 4.2; 3,3');
  await expect(page.locator('[data-outlet-calculator] [data-result="totalLengthM"]')).toContainText('15 м');
  await expect(page.locator('[data-outlet-calculator] [data-result="geometryCount"]')).toContainText('9');
  await page.locator('[data-outlet-calculator] [data-field="segmentLengths"]').fill('7,5;;3,3');
  await expect(page.locator('[data-outlet-calculator] [data-error]')).toBeVisible();
  await expect(page.locator('[data-outlet-calculator] [data-result="totalLengthM"]')).toHaveText('—');
  await page.locator('[data-outlet-calculator] [data-field="segmentLengths"]').fill('');
  await expect(page.locator('[data-outlet-calculator] [data-error]')).toBeVisible();
  await page.locator('[data-outlet-calculator] [data-field="segmentLengths"]').fill('7.5,4.2');
  await expect(page.locator('[data-outlet-calculator] [data-error]')).toBeVisible();
  await expect(page.locator('[data-outlet-calculator] [data-error]')).toContainText('используя десятичную запятую или точку');
  await page.locator('[data-outlet-calculator] [data-field="segmentLengths"]').fill('7,5; 4.2; 3,3');
  await expect(page.locator('[data-outlet-calculator] [data-error]')).toBeHidden();
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.waitForTimeout(100);
    await page.screenshot({ path: `.test-artifacts/overflow-${width}.png`, fullPage: true });
    const layout = await page.evaluate(() => ({ viewport: innerWidth, page: document.documentElement.scrollWidth }));
    expect(layout.page <= layout.viewport, JSON.stringify(layout)).toBeTruthy();
    const image = page.locator('.overflow-hero img');
    const currentSrc = await image.evaluate(img => img.currentSrc);
    expect(currentSrc).toContain(width <= 600 ? 'perelivnaya-sistema-mobile.svg' : 'perelivnaya-sistema-desktop.svg');
    await expect(image).toBeVisible();
    if (width === 390) await image.screenshot({ path: '.test-artifacts/overflow-hero-390.png' });
  }
  expect(pageErrors).toEqual([]);
});
